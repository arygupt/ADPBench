"""Simulation via Icarus Verilog, on the synthesized gate-level netlist.

Every problem gets two generated testbenches over the same netlist:

  score     every input port streams its beats back-to-back, `out_ready` is
            held high. This is the timing measurement: cycles from the first
            accepted input to the last accepted output, summed over the
            back-to-back transactions, with no testbench-imposed idle cycles.

  protocol  seeded input gaps on every port and seeded output backpressure,
            plus a conformance check that fails the run if the DUT drops or
            changes an output while `out_ready` is low. Results must still
            match the golden model; cycles are ignored.

Each input port has its own valid/ready handshake and its own length, so
matrix problems can stream operands of different sizes independently. The
testbench drives `transactions` back-to-back transactions without resetting;
the DUT must clear any per-transaction state when it emits the last output
word.

The simulated artifact is `netlist.v`, written by the pinned yosys flow after
elaboration at the problem's parameters.
"""

from __future__ import annotations

import hashlib
import os
import re
import subprocess
from .process import run_logged
from functools import lru_cache
from pathlib import Path
from shutil import which

from .problem import Problem

MAX_CYCLES = 200_000
RESULT_RE = re.compile(r"RESULT (\w+) CYCLES (\d+)")

TB_HEADER = """\
`timescale 1ns / 1ps
// Generated by ADPBench. Do not edit.
// Mode: {mode}
module tb;
  parameter LANES      = {LANES};
  parameter DATA_W     = {DATA_W};
  parameter ACC_W      = {ACC_W};
  parameter OUT_LEN    = {OUT_LEN};
  parameter TXNS       = {TXNS};
  parameter MAX_CYCLES = {MAX_CYCLES};
{port_params}

  reg clk = 1'b0;
  always #5 clk = ~clk;          // 100 MHz

  reg rst_n = 1'b0;
  reg txn_go = 1'b0;
  reg txn_active = 1'b0;
  integer txn = 0;

{port_decls}
  wire out_valid;
  reg  out_ready = {OUT_READY_INIT};
  wire [ACC_W-1:0] out_c;

  reg [ACC_W-1:0] out_words [0:TXNS*OUT_LEN-1];

  {top} u_dut (
    .clk(clk),
    .rst_n(rst_n),
{port_conns}
    .out_valid(out_valid),
    .out_ready(out_ready),
    .out_c(out_c)
  );

  reg protocol_error = 1'b0;
{port_lfsrs}
{port_drivers}
{out_ready_driver}
{protocol_check}
  integer out_count   = 0;
  integer total_words = 0;
  reg     txn_done    = 1'b0;
  reg     timed_out   = 1'b0;
  reg     counting    = 1'b0;
  reg     done        = 1'b0;
  integer cycle_count  = 0;
  integer total_cycles = 0;

  always @(posedge clk) begin
    if (!rst_n) begin
      out_count    <= 0;
      total_words  <= 0;
      txn_done     <= 1'b0;
      timed_out    <= 1'b0;
      counting     <= 1'b0;
      cycle_count  <= 0;
      total_cycles <= 0;
    end else begin
      if (txn_go) txn_done <= 1'b0;
      // Time is measured from when the transaction's inputs are first
      // presented, not from the first handshake, so a DUT cannot compute
      // before acknowledging for free.
      if (txn_active) counting <= 1'b1;
      if (counting) cycle_count <= cycle_count + 1;
      // Only outputs produced while a transaction is active count; a DUT that
      // presents stale data between transactions must not be credited for it.
      if (txn_active && out_valid && out_ready && total_words < TXNS*OUT_LEN) begin
        out_words[total_words] <= out_c;
        total_words <= total_words + 1;
        if (out_count + 1 == OUT_LEN) begin
          total_cycles <= total_cycles + cycle_count + 1;
          cycle_count  <= 0;
          counting     <= 1'b0;
          out_count    <= 0;
          txn_done     <= 1'b1;
{input_count_checks}
        end else begin
          out_count <= out_count + 1;
        end
      end else if (total_words >= TXNS*OUT_LEN && out_valid && out_ready) begin
        // More accepted output words than the task defines.
        protocol_error <= 1'b1;
      end
      if (total_cycles + cycle_count > MAX_CYCLES) timed_out <= 1'b1;
    end
  end

  integer t;
  initial begin
{readmem}
    repeat (4) @(posedge clk);
    @(negedge clk);
    rst_n = 1'b1;

    for (t = 0; t < TXNS; t = t + 1) begin
      @(negedge clk);
      txn        = t;
      txn_active = 1'b1;
      txn_go     = 1'b1;
      @(negedge clk);
      txn_go     = 1'b0;
      wait (txn_done || timed_out);
      txn_active = 1'b0;
      if (timed_out) begin
        if (protocol_error)
          $display("RESULT PROTOCOL CYCLES %0d", total_cycles + cycle_count);
        else
          $display("RESULT TIMEOUT CYCLES %0d", total_cycles + cycle_count);
        $finish;
      end
    end

    if (protocol_error) begin
      $display("RESULT PROTOCOL CYCLES %0d", total_cycles);
    end else begin
      $writememh("{out_file}", out_words);
      $display("RESULT OK CYCLES %0d", total_cycles);
    end
    $finish;
  end
endmodule
"""

PORT_PARAM = "  localparam {P}_LEN   = {plen};\n  localparam {P}_BEATS = {P}_LEN / LANES;"

PORT_DECL = """\
  wire [LANES*DATA_W-1:0] {p};
  reg                     {p}_valid = 1'b0;
  wire                    {p}_ready;
  reg  [LANES*DATA_W-1:0] {p}_mem [0:TXNS*{P}_BEATS-1];
  integer                 {p}_idx = 0;
  integer                 {p}_count = 0;
  assign {p} = {p}_mem[txn*{P}_BEATS + {p}_idx];"""

PORT_DRIVER = """\
  // Port `{p}`: {plen} elements per transaction, {pbeats} beats.
  integer  {p}_beat = 0;
  reg      {p}_active = 1'b0;
  reg [2:0] {p}_gap = 3'd0;
  always @(posedge clk) begin
    if (!rst_n) begin
      {p}_valid  <= 1'b0;
      {p}_active <= 1'b0;
      {p}_beat   <= 0;
      {p}_idx    <= 0;
      {p}_count  <= 0;
      {p}_gap    <= 3'd0;
    end else if (txn_go) begin
      {p}_valid  <= 1'b1;
      {p}_active <= 1'b1;
      {p}_beat   <= 0;
      {p}_idx    <= 0;
      {p}_count  <= 0;
      {p}_gap    <= 3'd0;
    end else if ({p}_active) begin
      if ({p}_valid) begin
        if ({p}_ready) begin
          {p}_count <= {p}_count + 1;
          if ({p}_beat == {P}_BEATS - 1) begin
            {p}_valid  <= 1'b0;
            {p}_active <= 1'b0;
          end else begin
            {p}_beat <= {p}_beat + 1;
            {p}_idx  <= {p}_idx + 1;
            {p}_valid <= {VALID_AFTER_BEAT};
            {p}_gap   <= {GAP_EXPR};
          end
        end
      end else if ({p}_gap != 3'd0) begin
        {p}_gap <= {p}_gap - 1;
      end else begin
        {p}_valid <= 1'b1;
      end
    end
  end"""

PORT_LFSR = """\
  reg [15:0] {p}_lfsr = {seed};
  always @(posedge clk) begin
    if (!rst_n) {p}_lfsr <= {seed};
    else {p}_lfsr <= {{ {p}_lfsr[14:0], {p}_lfsr[15] ^ {p}_lfsr[13] ^ {p}_lfsr[12] ^ {p}_lfsr[10] }};
  end"""

OUT_READY_DRIVER = """\
  // Deterministic hold-stability pressure: every presented output word is
  // held off for 1-4 seeded cycles before it can be accepted, and there is a
  // seeded low gap after each acceptance. A DUT that drops or mutates a word
  // while stalled is caught on its first word, not by luck.
  reg [15:0] out_lfsr = {seed};
  reg [2:0]  pressure_phase = 3'd0;
  reg [2:0]  pressure_count = 3'd0;
  always @(posedge clk) begin
    if (!rst_n) begin
      out_lfsr       <= {seed};
      out_ready      <= 1'b0;
      pressure_phase <= 3'd0;
      pressure_count <= 3'd0;
    end else begin
      out_lfsr <= {{ out_lfsr[14:0], out_lfsr[15] ^ out_lfsr[13] ^ out_lfsr[12] ^ out_lfsr[10] }};
      case (pressure_phase)
        3'd0: begin
          out_ready <= 1'b0;
          if (out_valid) begin
            pressure_count <= 3'd1 + out_lfsr[2:1];
            pressure_phase <= 3'd1;
          end
        end
        3'd1: begin
          out_ready <= 1'b0;
          if (pressure_count <= 3'd1) pressure_phase <= 3'd2;
          else pressure_count <= pressure_count - 3'd1;
        end
        default: begin
          out_ready      <= 1'b1;
          pressure_phase <= 3'd0;
        end
      endcase
      if (out_valid && out_ready) begin
        out_ready      <= 1'b0;
        pressure_phase <= 3'd0;
      end
    end
  end"""

PROTOCOL_CHECK = """\
  // Valid/ready conformance: while an output is presented and not accepted,
  // it must stay presented and unchanged.
  reg             out_stalled = 1'b0;
  reg [ACC_W-1:0] out_stalled_data = 0;
  always @(posedge clk) begin
    if (!rst_n) begin
      out_stalled      <= 1'b0;
      out_stalled_data <= 0;
      protocol_error   <= 1'b0;
    end else begin
      if (out_stalled && (!out_valid || out_c !== out_stalled_data))
        protocol_error <= 1'b1;
      if (out_valid && !out_ready) begin
        out_stalled      <= 1'b1;
        out_stalled_data <= out_c;
      end else begin
        out_stalled <= 1'b0;
      end
    end
  end"""

MODES = ("score", "protocol")


def _case_seed(case: int | str) -> int:
    """Map an int seed or directed-case name to a stable integer."""
    if isinstance(case, int):
        return case
    digest = hashlib.sha256(str(case).encode()).digest()
    return int.from_bytes(digest[:4], "big")


def _lfsr_seed(seed: int) -> int:
    """A nonzero 16-bit LFSR seed for a given evaluation seed."""
    return ((seed * 0x9E3779B1 + 0xACE1) & 0xFFFF) or 1


def _identifier(port: str) -> str:
    return re.sub(r"\W", "_", port).upper()


def render_tb(problem: Problem, seed: int = 0, mode: str = "score") -> str:
    if mode not in MODES:
        raise ValueError(f"unknown testbench mode {mode!r}")

    params = problem.params
    lanes = int(params["LANES"])
    protocol = mode == "protocol"
    ports = problem.input_ports
    lens = problem.input_lens

    port_params = []
    port_decls = []
    port_drivers = []
    port_conns = []
    readmem = []
    handshakes = []
    input_count_checks = []
    for index, port in enumerate(ports):
        upper = _identifier(port)
        plen = lens[port]
        if plen % lanes != 0:
            raise ValueError(
                f"{problem.name}: port {port} length {plen} is not a multiple of LANES={lanes}"
            )
        pbeats = plen // lanes
        port_params.append(PORT_PARAM.format(P=upper, plen=plen))
        port_decls.append(PORT_DECL.format(p=port, P=upper))
        port_drivers.append(
            PORT_DRIVER.format(
                p=port,
                P=upper,
                plen=plen,
                pbeats=pbeats,
                VALID_AFTER_BEAT="1'b0" if protocol else "1'b1",
                GAP_EXPR=f"3'd1 + {port}_lfsr[1:0]" if protocol else "3'd0",
            )
        )
        port_conns.append(
            f"    .{port}({port}),\n"
            f"    .{port}_valid({port}_valid),\n"
            f"    .{port}_ready({port}_ready),"
        )
        readmem.append(f'    $readmemh("{port}_beats.hex", {port}_mem);')
        handshakes.append(f"({port}_valid && {port}_ready)")
        input_count_checks.append(
            f"          if (({port}_count + (({port}_valid && {port}_ready) ? 1 : 0)) != {upper}_BEATS)\n"
            f"            protocol_error <= 1'b1;"
        )

    port_lfsrs = ""
    if protocol:
        base = _case_seed(seed)
        port_lfsrs = "\n".join(
            PORT_LFSR.format(p=port, seed=f"16'h{_lfsr_seed(base + 101 * (i + 1)):04x}")
            for i, port in enumerate(ports)
        )
        out_ready_driver = OUT_READY_DRIVER.format(seed=f"16'h{_lfsr_seed(base):04x}")
        protocol_check = PROTOCOL_CHECK
    else:
        out_ready_driver = ""
        protocol_check = ""

    return TB_HEADER.format(
        mode=mode,
        LANES=lanes,
        DATA_W=params["DATA_W"],
        ACC_W=params["ACC_W"],
        OUT_LEN=problem.out_len,
        TXNS=problem.transactions,
        MAX_CYCLES=MAX_CYCLES,
        port_params="\n".join(port_params),
        port_decls="\n".join(port_decls),
        port_conns="\n".join(port_conns),
        port_lfsrs=port_lfsrs,
        port_drivers="\n".join(port_drivers),
        OUT_READY_INIT="1'b0" if protocol else "1'b1",
        out_ready_driver=out_ready_driver,
        protocol_check=protocol_check,
        input_count_checks="\n".join(input_count_checks),
        any_handshake=" || ".join(handshakes) if handshakes else "1'b0",
        readmem="\n".join(readmem),
        top=problem.top,
        out_file=f"out_{mode}.hex",
    )


@lru_cache(maxsize=1)
def simlib_path() -> Path:
    """Locate yosys's simulation models for its internal cell types.

    `synth -noabc` emits `$_AND_`, `$_DFF_*`, ... instances. simlib.v is the
    behavioural model of those cells, so the netlist can be simulated as-is.
    """
    override = os.environ.get("ADPBENCH_SIMLIB")
    if override and Path(override).is_file():
        return Path(override)

    candidates: list[Path] = []
    config = which("yosys-config")
    if config:
        try:
            proc = subprocess.run(
                [config, "--datdir"], capture_output=True, text=True, timeout=30
            )
            if proc.returncode == 0 and proc.stdout.strip():
                candidates.append(Path(proc.stdout.strip()))
        except (OSError, subprocess.TimeoutExpired):
            pass

    binary = which("yosys")
    if binary:
        for parent in Path(binary).resolve().parents:
            candidates.append(parent / "share" / "yosys")
    candidates += [
        Path("/usr/share/yosys"),
        Path("/usr/local/share/yosys"),
        Path("/opt/homebrew/share/yosys"),
    ]

    seen: set[Path] = set()
    for base in candidates:
        if base in seen:
            continue
        seen.add(base)
        for rel in ("simlib.v", "techlibs/common/simlib.v", "simcells.v"):
            path = base / rel
            if path.is_file():
                return path
    raise RuntimeError(
        "cannot locate yosys simlib.v; set ADPBENCH_SIMLIB to its path"
    )


def simulate(
    problem: Problem,
    netlist: Path,
    workdir: Path,
    seed: int = 0,
    mode: str = "score",
) -> dict:
    """Compile the netlist against a generated testbench and run it.

    Returns {compiled, finished, timed_out, status, cycles, out_file, log},
    where status is OK, TIMEOUT, PROTOCOL, or NO RESULT.
    """
    if mode not in MODES:
        raise ValueError(f"unknown testbench mode {mode!r}")

    workdir = Path(workdir).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    tb = workdir / f"tb_{mode}.v"
    tb.write_text(render_tb(problem, seed, mode))
    out_file = workdir / f"out_{mode}.hex"

    lib = simlib_path()
    binary = f"sim_{mode}.vvp"
    build = run_logged(
        [
            "iverilog",
            "-g2012",
            "-s",
            "tb",
            "-o",
            binary,
            str(Path(netlist).resolve()),
            str(lib),
            tb.name,
        ],
        workdir, f"iverilog_{mode}",
    )
    if build["returncode"] != 0 or build["reason"]:
        return {
            "compiled": False,
            "finished": False,
            "timed_out": build["timed_out"],
            "status": "COMPILE",
            "cycles": -1,
            "out_file": out_file,
            "log": build["log"],
            "failure_kind": build["reason"],
        }

    run = run_logged(["vvp", binary], workdir, f"vvp_{mode}")
    if run["returncode"] != 0 or run["reason"]:
        return {
            "compiled": True,
            "finished": False,
            "timed_out": run["timed_out"],
            "status": "WALL_TIMEOUT" if run["timed_out"] else "TOOL_ERROR",
            "cycles": -1,
            "out_file": out_file,
            "log": run["log"],
            "failure_kind": run["reason"],
        }
    log = run["log"]
    match = RESULT_RE.search(log)

    if match is None:
        return {
            "compiled": True,
            "finished": False,
            "timed_out": False,
            "status": "NO RESULT",
            "cycles": -1,
            "out_file": out_file,
            "log": log,
        }

    status, cycles = match.group(1), int(match.group(2))
    return {
        "compiled": True,
        "finished": status == "OK",
        "timed_out": status == "TIMEOUT",
        "status": status,
        "cycles": cycles,
        "out_file": out_file,
        "log": log,
    }


@lru_cache(maxsize=1)
def tool_version() -> str:
    try:
        proc = subprocess.run(
            ["iverilog", "-V"], capture_output=True, text=True, timeout=30
        )
    except (OSError, subprocess.TimeoutExpired):
        return "unknown"
    lines = (proc.stdout + proc.stderr).strip().splitlines()
    return lines[0] if lines else "unknown"

"""Simulation via Icarus Verilog, on the synthesized gate-level netlist.

Every problem gets two generated testbenches over the same netlist:

  score     no input gaps, `out_ready` held high. This is the timing
            measurement: cycles from the first accepted input to the last
            accepted output, with no testbench-imposed idle cycles.

  protocol  seeded input gaps and seeded output backpressure, plus a
            conformance check that fails the run if the DUT drops or changes
            an output while `out_ready` is low. Results must still match the
            golden model; cycles are ignored. This is a correctness gate, not
            a timing measurement.

The simulated artifact is `netlist.v`, written by the pinned yosys flow after
elaboration at the problem's parameters. Synthesis and simulation therefore
judge one artifact, not two.
"""

from __future__ import annotations

import os
import re
import subprocess
from functools import lru_cache
from pathlib import Path
from shutil import which

from .problem import Problem

MAX_CYCLES = 200_000
RESULT_RE = re.compile(r"RESULT (\w+) CYCLES (\d+)")

TB_HEADER = """\
`timescale 1ns / 1ps
// Generated by ADPBench. Do not edit.
// Mode: {mode}
module tb;
  parameter LEN        = {LEN};
  parameter LANES      = {LANES};
  parameter DATA_W     = {DATA_W};
  parameter ACC_W      = {ACC_W};
  parameter OUT_LEN    = {OUT_LEN};
  parameter BEATS      = LEN / LANES;
  parameter WIDTH      = LANES * DATA_W;
  parameter MAX_CYCLES = {MAX_CYCLES};

  reg clk = 1'b0;
  always #5 clk = ~clk;          // 100 MHz

  reg rst_n = 1'b0;

  reg  in_valid = 1'b0;
  wire in_ready;
{input_decls}
  wire out_valid;
  reg  out_ready = {OUT_READY_INIT};
  wire [ACC_W-1:0] out_c;

{beat_mems}
  reg [ACC_W-1:0] out_words [0:OUT_LEN-1];

  // The DUT is the elaborated netlist, already specialized at the problem's
  // parameters by synthesis. No parameter overrides here: the testbench must
  // drive exactly the hardware that was counted.
  {top} u_dut (
    .clk(clk),
    .rst_n(rst_n),
    .in_valid(in_valid),
    .in_ready(in_ready),
{port_conns}
    .out_valid(out_valid),
    .out_ready(out_ready),
    .out_c(out_c)
  );

  reg protocol_error = 1'b0;
{lfsr_driver}
{protocol_check}
  reg     counting    = 1'b0;
  reg     done        = 1'b0;
  integer cycle_count = 0;
  integer total_cycles = 0;
  integer out_count   = 0;
  integer i;
"""

TB_FOOTER = """
  // Absolute wall-clock guard. `cycle_count` only advances once a handshake
  // has happened, so it cannot detect a DUT that never asserts in_ready.
  always @(posedge clk)
    if (rst_n) total_cycles <= total_cycles + 1;

  always @(posedge clk) begin
    if (!rst_n) begin
      counting    <= 1'b0;
      done        <= 1'b0;
      cycle_count <= 0;
      out_count   <= 0;
    end else begin
      if (in_valid && in_ready) counting <= 1'b1;
      if (counting) cycle_count <= cycle_count + 1;
      // Capture exactly OUT_LEN words. A DUT that holds out_valid high forever
      // must not be able to run the counter past the expected result.
      if (out_valid && out_ready && out_count < OUT_LEN) begin
        out_words[out_count] <= out_c;
        out_count <= out_count + 1;
        if (out_count + 1 == OUT_LEN) begin
          counting <= 1'b0;
          done     <= 1'b1;
        end
      end
      if (total_cycles > MAX_CYCLES) done <= 1'b1;
    end
  end

  initial begin
{readmem}
    repeat (4) @(posedge clk);
    @(negedge clk);
    rst_n = 1'b1;

    @(negedge clk);
    for (i = 0; i < BEATS; i = i + 1) begin
{stimulus}
      in_valid = 1'b1;
      @(posedge clk);
      while (!in_ready) begin
        @(posedge clk);
        if (total_cycles > MAX_CYCLES) begin
          $display("RESULT TIMEOUT CYCLES %0d", cycle_count);
          $finish;
        end
      end
      @(negedge clk);
      in_valid = 1'b0;
{gap}    end
    in_valid = 1'b0;

    wait (done);
    if (protocol_error) begin
      $display("RESULT PROTOCOL CYCLES %0d", cycle_count);
    end else if (out_count == OUT_LEN) begin
      $writememh("{out_file}", out_words);
      $display("RESULT OK CYCLES %0d", cycle_count);
    end else begin
      $display("RESULT TIMEOUT CYCLES %0d", cycle_count);
    end
    $finish;
  end
endmodule
"""

LFSR_DRIVER = """
  // Seeded backpressure: one cycle ready, then 1-4 cycles stalled.
  reg [15:0] lfsr = {LFSR_SEED};
  reg [2:0]  stall_run = 3'd0;
  always @(posedge clk) begin
    if (!rst_n) begin
      lfsr      <= {LFSR_SEED};
      stall_run <= 3'd0;
      out_ready <= 1'b0;
    end else begin
      lfsr <= {{lfsr[14:0], lfsr[15] ^ lfsr[13] ^ lfsr[12] ^ lfsr[10]}};
      if (stall_run == 3'd0) begin
        out_ready <= 1'b1;
        stall_run <= 3'd1 + lfsr[2:1];
      end else begin
        out_ready <= 1'b0;
        stall_run <= stall_run - 3'd1;
      end
    end
  end
"""

PROTOCOL_CHECK = """
  // Valid/ready conformance: while an output is presented and not accepted,
  // it must stay presented and unchanged.
  reg             out_stalled = 1'b0;
  reg [ACC_W-1:0] out_stalled_data = 0;
  always @(posedge clk) begin
    if (!rst_n) begin
      out_stalled      <= 1'b0;
      out_stalled_data <= 0;
      protocol_error   <= 1'b0;
    end else begin
      if (out_stalled && (!out_valid || out_c !== out_stalled_data))
        protocol_error <= 1'b1;
      if (out_valid && !out_ready) begin
        out_stalled      <= 1'b1;
        out_stalled_data <= out_c;
      end else begin
        out_stalled <= 1'b0;
      end
    end
  end
"""

GAP = """\
      if (i != BEATS - 1) begin
        @(posedge clk);
        repeat (lfsr[1:0]) @(posedge clk);   // seeded input gap
      end
"""

MODES = ("score", "protocol")


def _lfsr_seed(seed: int) -> int:
    """A nonzero 16-bit LFSR seed for a given evaluation seed."""
    return ((seed * 0x9E3779B1 + 0xACE1) & 0xFFFF) or 1


def render_tb(problem: Problem, seed: int = 0, mode: str = "score") -> str:
    if mode not in MODES:
        raise ValueError(f"unknown testbench mode {mode!r}")

    params = problem.params
    ports = problem.input_ports
    protocol = mode == "protocol"

    body = TB_HEADER.format(
        mode=mode,
        LEN=params["LEN"],
        LANES=params["LANES"],
        DATA_W=params["DATA_W"],
        ACC_W=params["ACC_W"],
        OUT_LEN=problem.out_len,
        MAX_CYCLES=MAX_CYCLES,
        OUT_READY_INIT="1'b0" if protocol else "1'b1",
        LFSR_SEED=f"16'h{_lfsr_seed(seed):04x}",
        top=problem.top,
        input_decls="\n".join(
            f"  reg  [LANES*DATA_W-1:0] {p} = 0;" for p in ports
        ),
        beat_mems="\n".join(
            f"  reg [LANES*DATA_W-1:0] {p}_beats [0:BEATS-1];" for p in ports
        ),
        port_conns="\n".join(f"    .{p}({p})," for p in ports),
        lfsr_driver=LFSR_DRIVER.format(LFSR_SEED=f"16'h{_lfsr_seed(seed):04x}")
        if protocol
        else "",
        protocol_check=PROTOCOL_CHECK if protocol else "",
    )
    return body + TB_FOOTER.format(
        readmem="\n".join(
            f'    $readmemh("{p}_beats.hex", {p}_beats);' for p in ports
        ),
        stimulus="\n".join(f"      {p} = {p}_beats[i];" for p in ports),
        gap=GAP if protocol else "",
        out_file=f"out_{mode}.hex",
    )


@lru_cache(maxsize=1)
def simlib_path() -> Path:
    """Locate yosys's simulation models for its internal cell types.

    `synth -noabc` emits `$_AND_`, `$_DFF_*`, ... instances. simlib.v is the
    behavioural model of those cells, so the netlist can be simulated as-is.
    """
    override = os.environ.get("ADPBENCH_SIMLIB")
    if override and Path(override).is_file():
        return Path(override)

    candidates: list[Path] = []
    config = which("yosys-config")
    if config:
        try:
            proc = subprocess.run(
                [config, "--datdir"], capture_output=True, text=True, timeout=30
            )
            if proc.returncode == 0 and proc.stdout.strip():
                candidates.append(Path(proc.stdout.strip()))
        except (OSError, subprocess.TimeoutExpired):
            pass

    binary = which("yosys")
    if binary:
        for parent in Path(binary).resolve().parents:
            candidates.append(parent / "share" / "yosys")
    candidates += [
        Path("/usr/share/yosys"),
        Path("/usr/local/share/yosys"),
        Path("/opt/homebrew/share/yosys"),
    ]

    seen: set[Path] = set()
    for base in candidates:
        if base in seen:
            continue
        seen.add(base)
        for rel in ("simlib.v", "techlibs/common/simlib.v", "simcells.v"):
            path = base / rel
            if path.is_file():
                return path
    raise RuntimeError(
        "cannot locate yosys simlib.v; set ADPBENCH_SIMLIB to its path"
    )


def simulate(
    problem: Problem,
    netlist: Path,
    workdir: Path,
    seed: int = 0,
    mode: str = "score",
) -> dict:
    """Compile the netlist against a generated testbench and run it.

    Returns {compiled, finished, timed_out, status, cycles, out_file, log},
    where status is OK, TIMEOUT, PROTOCOL, or NO RESULT.
    """
    if mode not in MODES:
        raise ValueError(f"unknown testbench mode {mode!r}")

    workdir = Path(workdir).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    tb = workdir / f"tb_{mode}.v"
    tb.write_text(render_tb(problem, seed, mode))
    out_file = workdir / f"out_{mode}.hex"

    lib = simlib_path()
    binary = f"sim_{mode}.vvp"
    build = subprocess.run(
        [
            "iverilog",
            "-g2012",
            "-s",
            "tb",
            "-o",
            binary,
            str(Path(netlist).resolve()),
            str(lib),
            tb.name,
        ],
        cwd=workdir,
        capture_output=True,
        text=True,
        timeout=600,
    )
    if build.returncode != 0:
        return {
            "compiled": False,
            "finished": False,
            "timed_out": False,
            "status": "COMPILE",
            "cycles": -1,
            "out_file": out_file,
            "log": build.stdout + build.stderr,
        }

    try:
        run = subprocess.run(
            ["vvp", binary],
            cwd=workdir,
            capture_output=True,
            text=True,
            timeout=600,
        )
    except subprocess.TimeoutExpired as exc:
        return {
            "compiled": True,
            "finished": False,
            "timed_out": True,
            "status": "TIMEOUT",
            "cycles": -1,
            "out_file": out_file,
            "log": f"[adpbench] vvp exceeded its time limit\n{exc}",
        }
    log = run.stdout + run.stderr
    match = RESULT_RE.search(log)

    if match is None:
        return {
            "compiled": True,
            "finished": False,
            "timed_out": False,
            "status": "NO RESULT",
            "cycles": -1,
            "out_file": out_file,
            "log": log,
        }

    status, cycles = match.group(1), int(match.group(2))
    return {
        "compiled": True,
        "finished": status == "OK",
        "timed_out": status == "TIMEOUT",
        "status": status,
        "cycles": cycles,
        "out_file": out_file,
        "log": log,
    }


@lru_cache(maxsize=1)
def tool_version() -> str:
    try:
        proc = subprocess.run(
            ["iverilog", "-V"], capture_output=True, text=True, timeout=30
        )
    except (OSError, subprocess.TimeoutExpired):
        return "unknown"
    lines = (proc.stdout + proc.stderr).strip().splitlines()
    return lines[0] if lines else "unknown"

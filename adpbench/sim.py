"""Simulation via Icarus Verilog.

The testbench is generated from the problem spec so that every problem gets the
same protocol driver: hold every input port together on one valid/ready
handshake, apply periodic output backpressure, and count cycles from the first
accepted input to the last accepted output.

The DUT never sees this file, but it defines the contract the DUT must meet.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

from .problem import Problem

MAX_CYCLES = 200_000
RESULT_RE = re.compile(r"RESULT (\w+) CYCLES (\d+)")

TB_TEMPLATE = """\
`timescale 1ns / 1ps
// Generated by ADPBench. Do not edit.
module tb;
  parameter LEN        = {LEN};
  parameter LANES      = {LANES};
  parameter DATA_W     = {DATA_W};
  parameter ACC_W      = {ACC_W};
  parameter OUT_LEN    = {OUT_LEN};
  parameter BEATS      = LEN / LANES;
  parameter WIDTH      = LANES * DATA_W;
  parameter MAX_CYCLES = {MAX_CYCLES};

  reg clk = 1'b0;
  always #5 clk = ~clk;          // 100 MHz

  reg rst_n = 1'b0;

  reg  in_valid = 1'b0;
  wire in_ready;
{input_decls}
  wire out_valid;
  reg  out_ready = 1'b1;
  wire [ACC_W-1:0] out_c;

{beat_mems}
  reg [ACC_W-1:0] out_words [0:OUT_LEN-1];

  {top} #(
    .LEN(LEN), .LANES(LANES), .DATA_W(DATA_W), .ACC_W(ACC_W)
  ) u_dut (
    .clk(clk),
    .rst_n(rst_n),
    .in_valid(in_valid),
    .in_ready(in_ready),
{port_conns}
    .out_valid(out_valid),
    .out_ready(out_ready),
    .out_c(out_c)
  );

  // Periodic output backpressure so a DUT that ignores out_ready is caught.
  reg [1:0] bp = 2'd0;
  always @(posedge clk) begin
    if (!rst_n) begin
      bp        <= 2'd0;
      out_ready <= 1'b1;
    end else begin
      bp        <= bp + 1'b1;
      out_ready <= (bp != 2'd3);
    end
  end

  reg     counting    = 1'b0;
  reg     done        = 1'b0;
  integer cycle_count = 0;
  integer total_cycles = 0;
  integer out_count   = 0;
  integer i;

  // Absolute wall-clock guard. `cycle_count` only advances once a handshake
  // has happened, so it cannot detect a DUT that never asserts in_ready.
  always @(posedge clk)
    if (rst_n) total_cycles <= total_cycles + 1;

  always @(posedge clk) begin
    if (!rst_n) begin
      counting    <= 1'b0;
      done        <= 1'b0;
      cycle_count <= 0;
      out_count   <= 0;
    end else begin
      if (in_valid && in_ready) counting <= 1'b1;
      if (counting) cycle_count <= cycle_count + 1;
      // Capture exactly OUT_LEN words. A DUT that holds out_valid high forever
      // must not be able to run the counter past the expected result.
      if (out_valid && out_ready && out_count < OUT_LEN) begin
        out_words[out_count] <= out_c;
        out_count <= out_count + 1;
        if (out_count + 1 == OUT_LEN) begin
          counting <= 1'b0;
          done     <= 1'b1;
        end
      end
      if (total_cycles > MAX_CYCLES) done <= 1'b1;
    end
  end

  initial begin
{readmem}
    repeat (4) @(posedge clk);
    @(negedge clk);
    rst_n = 1'b1;

    @(negedge clk);
    for (i = 0; i < BEATS; i = i + 1) begin
{stimulus}
      in_valid = 1'b1;
      @(posedge clk);
      while (!in_ready) begin
        @(posedge clk);
        if (total_cycles > MAX_CYCLES) begin
          $display("RESULT TIMEOUT CYCLES %0d", cycle_count);
          $finish;
        end
      end
      @(negedge clk);
    end
    in_valid = 1'b0;

    wait (done);
    if (out_count == OUT_LEN) begin
      $writememh("out.hex", out_words);
      $display("RESULT OK CYCLES %0d", cycle_count);
    end else begin
      $display("RESULT TIMEOUT CYCLES %0d", cycle_count);
    end
    $finish;
  end
endmodule
"""


def render_tb(problem: Problem) -> str:
    params = problem.params
    ports = problem.input_ports

    return TB_TEMPLATE.format(
        LEN=params["LEN"],
        LANES=params["LANES"],
        DATA_W=params["DATA_W"],
        ACC_W=params["ACC_W"],
        OUT_LEN=problem.out_len,
        MAX_CYCLES=MAX_CYCLES,
        top=problem.top,
        input_decls="\n".join(
            f"  reg  [LANES*DATA_W-1:0] {p} = 0;" for p in ports
        ),
        beat_mems="\n".join(
            f"  reg [LANES*DATA_W-1:0] {p}_beats [0:BEATS-1];" for p in ports
        ),
        port_conns="\n".join(f"    .{p}({p})," for p in ports),
        readmem="\n".join(
            f'    $readmemh("{p}_beats.hex", {p}_beats);' for p in ports
        ),
        stimulus="\n".join(f"      {p} = {p}_beats[i];" for p in ports),
    )


def simulate(problem: Problem, rtl_paths: list[Path], workdir: Path) -> dict:
    """Compile and run. Returns {compiled, finished, timed_out, cycles, log}."""
    workdir = Path(workdir).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    tb = workdir / "tb.v"
    tb.write_text(render_tb(problem))

    build = subprocess.run(
        [
            "iverilog",
            "-g2012",
            "-s",
            "tb",
            "-o",
            "sim.vvp",
            *[str(Path(p).resolve()) for p in rtl_paths],
            "tb.v",
        ],
        cwd=workdir,
        capture_output=True,
        text=True,
        timeout=600,
    )
    if build.returncode != 0:
        return {
            "compiled": False,
            "finished": False,
            "timed_out": False,
            "cycles": -1,
            "log": build.stdout + build.stderr,
        }

    try:
        run = subprocess.run(
            ["vvp", "sim.vvp"],
            cwd=workdir,
            capture_output=True,
            text=True,
            timeout=600,
        )
    except subprocess.TimeoutExpired as exc:
        return {
            "compiled": True,
            "finished": False,
            "timed_out": True,
            "cycles": -1,
            "log": f"[adpbench] vvp exceeded its time limit\n{exc}",
        }
    log = run.stdout + run.stderr
    match = RESULT_RE.search(log)

    if match is None:
        return {
            "compiled": True,
            "finished": False,
            "timed_out": False,
            "cycles": -1,
            "log": log,
        }

    status, cycles = match.group(1), int(match.group(2))
    return {
        "compiled": True,
        "finished": status == "OK",
        "timed_out": status != "OK",
        "cycles": cycles,
        "log": log,
    }

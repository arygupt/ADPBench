@lru_cache(maxsize=1)
def simlib_path() -> Path:
    """Locate yosys's simulation models for its internal cell types.

    `synth -noabc` emits `$_AND_`, `$_DFF_*`, ... instances. simlib.v is the
    behavioural model of those cells, so the netlist can be simulated as-is.
    `ADPBENCH_SIMLIB` overrides the search.
    """
    override = os.environ.get("ADPBENCH_SIMLIB")
    if override and Path(override).is_file():
        return Path(override)

    candidates: list[Path] = []
    config = which("yosys-config")
    if config:
        try:
            proc = subprocess.run([config, "--datdir"], capture_output=True, text=True, timeout=30)
            if proc.returncode == 0 and proc.stdout.strip():
                candidates.append(Path(proc.stdout.strip()))
        except (OSError, subprocess.TimeoutExpired):
            pass

    binary = which("yosys")
    if binary:
        for parent in Path(binary).resolve().parents:
            candidates.append(parent / "share" / "yosys")
    candidates += [
        Path("/usr/share/yosys"),
        Path("/usr/local/share/yosys"),
        Path("/opt/homebrew/share/yosys"),
    ]

    seen: set[Path] = set()
    for base in candidates:
        if base in seen:
            continue
        seen.add(base)
        for relative in ("simlib.v", "techlibs/common/simlib.v", "simcells.v"):
            path = base / relative
            if path.is_file():
                return path
    raise RuntimeError("cannot locate yosys simlib.v; set ADPBENCH_SIMLIB to its path")


def simulate(
    problem: Problem,
    netlist: Path,
    workdir: Path,
    seed: int | str = 0,
    mode: str = "score",
    deadline_at: float | None = None,
) -> dict:
    """Compile the netlist against a generated testbench and run it.

    Returns {"compiled", "finished", "timed_out", "status", "cycles",
    "out_file", "log"}, plus "failure_kind" when a tool itself failed.
    `status` is what the testbench reported (OK, TIMEOUT, PROTOCOL), or
    NO RESULT, COMPILE, WALL_TIMEOUT, or TOOL_ERROR.
    """
    if mode not in MODES:
        raise ValueError(f"unknown testbench mode {mode!r}")

    workdir = Path(workdir).resolve()
    workdir.mkdir(parents=True, exist_ok=True)
    testbench = workdir / f"tb_{mode}.v"
    testbench.write_text(render_tb(problem, seed, mode))
    out_file = workdir / f"out_{mode}.hex"
    binary = f"sim_{mode}.vvp"

    compile_command = [
        "iverilog", "-g2012", "-s", "tb", "-o", binary,
        str(Path(netlist).resolve()), str(simlib_path()), testbench.name,
    ]
    build = run_logged(compile_command, workdir, f"iverilog_{mode}", deadline_at=deadline_at)
    if build["returncode"] != 0 or build["reason"]:
        return {
            "compiled": False,
            "finished": False,
            "timed_out": build["timed_out"],
            "status": "COMPILE",
            "cycles": -1,
            "out_file": out_file,
            "log": build["log"],
            "failure_kind": build["reason"],
        }

    run = run_logged(["vvp", binary], workdir, f"vvp_{mode}", deadline_at=deadline_at)
    if run["returncode"] != 0 or run["reason"]:
        return {
            "compiled": True,
            "finished": False,
            "timed_out": run["timed_out"],
            "status": "WALL_TIMEOUT" if run["timed_out"] else "TOOL_ERROR",
            "cycles": -1,
            "out_file": out_file,
            "log": run["log"],
            "failure_kind": run["reason"],
        }

    match = RESULT_LINE.search(run["log"])
    if match is None:
        return {
            "compiled": True,
            "finished": False,
            "timed_out": False,
            "status": "NO RESULT",
            "cycles": -1,
            "out_file": out_file,
            "log": run["log"],
        }

    status, cycles = match.group(1), int(match.group(2))
    return {
        "compiled": True,
        "finished": status == "OK",
        "timed_out": status == "TIMEOUT",
        "status": status,
        "cycles": cycles,
        "out_file": out_file,
        "log": run["log"],
    }


@lru_cache(maxsize=1)
def tool_version() -> str:
    """First line of `iverilog -V`, or "unknown"."""
    try:
        proc = subprocess.run(["iverilog", "-V"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return "unknown"
    lines = (proc.stdout + proc.stderr).strip().splitlines()
    return lines[0] if lines else "unknown"
